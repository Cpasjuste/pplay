#!/usr/bin/env python3
"""Generates src/subtitle_tables.cpp: double byte code page -> UTF-16 tables used
by pplay to turn legacy encoded subtitle files into UTF-8 (the PS4 mpv is built
without iconv). Run: python3 tools/gen_subtitle_tables.py > src/subtitle_tables.cpp"""
import sys

# name, python codec, lead range, trail range
ENC = [
    ("cp949", "cp949", 0x81, 0xFE, 0x41, 0xFE),
    ("cp932", "cp932", 0x81, 0xFC, 0x40, 0xFC),
    ("gbk",   "gbk",   0x81, 0xFE, 0x40, 0xFE),
    ("big5",  "cp950", 0x81, 0xFE, 0x40, 0xFE),
]

out = ["// GENERATED by tools/gen_subtitle_tables.py - do not edit",
       '#include "subtitle_tables.h"', "", "namespace pplay {", ""]
for name, codec, l0, l1, t0, t1 in ENC:
    vals = []
    for lead in range(l0, l1 + 1):
        for trail in range(t0, t1 + 1):
            try:
                s = bytes([lead, trail]).decode(codec)
                v = ord(s) if len(s) == 1 and ord(s) < 0x10000 else 0
            except Exception:
                v = 0
            vals.append(v)
    out.append(f"static const unsigned short tbl_{name}[] = {{")
    for i in range(0, len(vals), 16):
        out.append("    " + ",".join(f"0x{v:04X}" for v in vals[i:i + 16]) + ",")
    out.append("};")
    out.append(f"const DbcsTable table_{name} = {{0x{l0:02X}, 0x{l1:02X}, 0x{t0:02X}, 0x{t1:02X}, tbl_{name}}};")
    out.append("")
out.append("}")
print("\n".join(out))
